// Generates src/components/icons/brand-paths.ts from the simple-icons package
// (CC0). Run with `npm run icons` after adding a slug below.
import { writeFileSync } from "node:fs";
import * as icons from "simple-icons";

const SLUGS = {
  html: "siHtml5",
  css: "siCss",
  javascript: "siJavascript",
  typescript: "siTypescript",
  react: "siReact",
  nextjs: "siNextdotjs",
  reactRouter: "siReactrouter",
  tailwind: "siTailwindcss",
  redux: "siRedux",
  sass: "siSass",
  vue: "siVuedotjs",
  firebase: "siFirebase",
  laravel: "siLaravel",
  bootstrap: "siBootstrap",
  zod: "siZod",
  radix: "siRadixui",
  node: "siNodedotjs",
  git: "siGit",
  github: "siGithub",
  figma: "siFigma",
  facebook: "siFacebook",
  instagram: "siInstagram",
};

const entries = Object.entries(SLUGS).map(([key, exportName]) => {
  const icon = icons[exportName];
  if (!icon) throw new Error(`simple-icons has no export ${exportName}`);
  return `  ${key}: ${JSON.stringify(icon.path)},`;
});

writeFileSync(
  new URL("../src/components/icons/brand-paths.ts", import.meta.url),
  `// Generated by scripts/generate-brand-icons.mjs from simple-icons (CC0). Do not edit.
export const BRAND_PATHS = {
${entries.join("\n")}
} as const;

export type BrandPathName = keyof typeof BRAND_PATHS;
`,
);
console.log(`Wrote ${entries.length} icon paths`);
